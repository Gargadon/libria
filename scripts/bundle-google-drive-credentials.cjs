const fs = require('node:fs');
const path = require('node:path');
const { sealCredentials, openCredentials } = require('../electron/credential-blob');

function bundle(inputPath, outputPath) {
  let config;
  try { config = JSON.parse(fs.readFileSync(inputPath, 'utf8')); }
  catch { throw new Error('No se pudo leer la configuración OAuth local.'); }
  if (typeof config.client_id !== 'string' || !config.client_id.endsWith('.apps.googleusercontent.com') ||
      typeof config.client_secret !== 'string' || !config.client_secret.trim() || config.client_secret.length > 4096) {
    throw new Error('Completa client_id y client_secret en google-drive-config.json.');
  }
  const credentials = { clientId: config.client_id, clientSecret: config.client_secret };
  const blob = sealCredentials(credentials);
  const decoded = openCredentials(blob);
  if (decoded.clientId !== credentials.clientId || decoded.clientSecret !== credentials.clientSecret) {
    throw new Error('Falló la comprobación del blob OAuth.');
  }
  const source = '// Generated by scripts/bundle-google-drive-credentials.cjs. No user tokens.\n' +
    '// AES-GCM with distributed key shares: obfuscation, not a confidential secret.\n' +
    'module.exports = ' + JSON.stringify(blob, null, 2) + ';\n';
  const temporary = outputPath + '.tmp';
  try {
    fs.writeFileSync(temporary, source, { mode: 0o600 });
    fs.renameSync(temporary, outputPath);
  } finally { if (fs.existsSync(temporary)) fs.unlinkSync(temporary); }
}

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  try {
    bundle(path.join(root, 'google-drive-config.json'), path.join(root, 'electron', 'google-drive-credentials.cjs'));
    console.log('Blob OAuth generado y comprobado. No se imprimieron las credenciales.');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
module.exports = { bundle };
